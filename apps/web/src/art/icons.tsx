const ICON_PALETTE = { o: 'currentColor' };

export const ICON_NAMES = Object.keys(ROWS) as IconName[];

export const ICONS = {} as Record<IconName, Sprite>;
for (const name of ICON_NAMES) ICONS[name] = { w: 12, h: 12, rows: ROWS[name], palette: ICON_PALETTE };

export function isIconName(name: string): name is IconName {
  return name in ROWS;
}

/** Maps stored area icon names (e.g. seed 'home') to an icon, falling back to a star. */
export function areaIcon(name: string | undefined): IconName {
  if (name === 'home') return 'house';
  return name && isIconName(name) ? name : 'star';
}

export interface IconProps { name: IconName; size?: number; title?: string; className?: string }

/** Pixel icon. Prefer sizes that are multiples of 12 (24, 36) for crisp pixels. */
export function Icon({ name, size = 24, title, className }: IconProps) {
  return (
    <PixelSprite
      sprite={ICONS[name]}
      scale={size / 12}
      title={title}
      className={className ? `icon ${className}` : 'icon'}
    />
  );
}
